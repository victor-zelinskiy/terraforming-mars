/*
 * A MODULE's OWN NET ENDED A WAIT — counted, and not yet judged.
 *
 * A scene that waits for something of its own (a cube's touchdown, a sitting telling its enactment, a ledger's next
 * row) keeps a net over that wait, and when the net ends it the module degrades honestly and says so under ITS OWN
 * tag — a NOTE (`common/diagnostics/classify.ts`): a breadcrumb nobody counts. The audit of what reaches the collector
 * (2026-11-19) could not decide three of them by reading: each is either a lost signal upstream (a stall the player
 * sat through — the deck pick's deal was exactly such a note, and the night its ceiling became a wait of the graph it
 * named a real eight-second stop) or a designed road that is taken every time a flight has nowhere to land.
 *
 * `netEnded(id, what)` prints `[net-ended] <id> — <what>`: a stall-family line whose one shape is tier `info` — a
 * RECORD of every walk and every console export (class `net-ended/ended/<id>`), never an event. So the matrix says
 * how often each comes and in which walks, and the walk is read. THE DOOR IS A WAITING ROOM: a line leaves it either
 * as a ceiling wait of the graph (`waitGraph/ceilingWait.ts` — a defect on a page that painted) or as a designed
 * fallback with its reason written where it is taken — and a line that stays here longer than a matrix is a decision
 * nobody made.
 *
 *   · `id`   — `<module>:<what-ended>`, FIXED words (it is the class): `banner-stage:cube-touchdown`.
 *   · `what` — the sentence for a reader, with the particulars. Never a seat's id or a name.
 */
export function netEnded(id: string, what: string): void {
  console.warn(`[net-ended] ${id} — ${what}`);
}
